/**
 * Fonction pour obtenir la traduction française d'un type de lieu
 * @param {string} type - Le type de lieu Google Places
 * @returns {string} - La traduction française
 */
function getFrenchType(type) {
    return placeTypeTranslations[type] || type.charAt(0).toUpperCase() + type.slice(1).replace(/_/g, ' ');
}

